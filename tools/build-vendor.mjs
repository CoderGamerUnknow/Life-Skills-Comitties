/**
 * Vendor the browser build of @vercel/blob/client into public/js/vendor/.
 *
 * The admin panel is plain HTML/CSS/JS served straight from public/ with no
 * bundler, but uploading a video larger than 4.5 MB has to go straight from the
 * browser to Vercel Blob (Vercel Functions cap request bodies at 4.5 MB). The
 * official client helper does that handshake, so the built file is checked in
 * and imported by public/js/admin.js as an ES module.
 *
 * Usage: npm run build:vendor   (re-run after upgrading @vercel/blob)
 */

import * as esbuild from "esbuild";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUT = new URL("../public/js/vendor/vercel-blob-client.mjs", import.meta.url);

const { dependencies } = JSON.parse(
  await readFile(new URL("../package.json", import.meta.url), "utf8")
);
const version = String(dependencies["@vercel/blob"] || "unknown");

await esbuild.build({
  entryPoints: [fileURLToPath(new URL("./build/blob-client-entry.js", import.meta.url))],
  bundle: true,
  outfile: fileURLToPath(OUT),
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  logLevel: "warning",
  banner: {
    js: `// Generated by tools/build-vendor.mjs — do not edit.\n// @vercel/blob ${version} (client build, browser platform)\n`,
  },
});

console.log(`Vendored @vercel/blob ${version} -> ${fileURLToPath(OUT)}`);
